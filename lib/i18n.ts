export function translateMessage(
  lang: Lang,
  message: string | undefined
): string | undefined {
  if (!message) return message;
  // database gates: a blocking request is still pending on the file / the visa
  if (/(company_review|visa_review):.*still pending/.test(message)) {
    return DICTIONARY[lang]["correction.blocked"] ?? message;
  }
  const key = VALIDATION_MESSAGE_MAP[message];
  if (!key) return message;
  return DICTIONARY[lang][key] ?? message;
}

export function translateEmirate(lang: Lang, emirate: string): string {
  return DICTIONARY[lang][`emirate.${emirate}`] ?? emirate;
}

/**
 * Generic lookup for the visa module's small enum-style option labels
 * (visa type, contract type, Golden Visa category/duration, domestic job
 * type, family relation, appointment slot, typing/medical center), all
 * stored as `<prefix>.<id>` dictionary keys (e.g. `visa.contract.cdi`,
 * `visa.center.al-barsha-medical`). Falls back to the raw id so nothing
 * ever renders blank if a key is momentarily missing.
 */
export function translateOption(lang: Lang, prefix: string, id: string): string {
  return DICTIONARY[lang][`${prefix}.${id}`] ?? id;
}

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>
): string {
  let str = DICTIONARY[lang][key] ?? DICTIONARY[DEFAULT_LANG][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}
